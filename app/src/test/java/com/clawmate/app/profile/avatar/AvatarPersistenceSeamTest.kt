package com.clawmate.app.profile.avatar

import com.clawmate.app.profile.avatar.data.FakeAvatarAssetRepository
import com.clawmate.app.profile.avatar.data.asset.AvatarAssetLimits
import com.clawmate.app.profile.avatar.data.asset.AvatarAssetStorageLogic
import com.clawmate.app.profile.avatar.domain.AvatarGenerationMode
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Device-free tests for the local asset **result path** (migration row A2):
 * persisting real provider-generated bytes through the repository records a
 * `seedream` version, advances state, and enforces the same bounded/validated
 * rules as a user import.
 */
class AvatarPersistenceSeamTest {

    @Test
    fun `persistGeneratedImage records a seedream version and advances state`() = runTest {
        val repo = FakeAvatarAssetRepository()
        val bytes = ByteArray(128) { it.toByte() }
        val result = repo.persistGeneratedImage(
            bytes = bytes,
            outputFormat = "jpeg",
            mode = AvatarGenerationMode.TEXT_TO_IMAGE,
            model = "seedream-3",
            prompt = "生成一个数字分身",
            profileHash = "hash-123",
        )
        assertTrue(result.success)
        val version = result.version!!
        assertTrue(version.versionId.startsWith("seedream-"))
        assertEquals("seedream", version.provider)
        assertEquals("seedream-3", version.model)
        assertEquals("hash-123", version.profileSnapshotHash)
        assertTrue(version.imageRelativePath.endsWith(".jpg"))

        val state = result.state
        assertEquals(version.versionId, state.currentVersionId)
        assertEquals(com.clawmate.app.profile.avatar.domain.AvatarStatusToken.CURRENT, state.status)
    }

    @Test
    fun `empty and oversized generated bytes are rejected never persisted`() = runTest {
        val repo = FakeAvatarAssetRepository()
        val empty = repo.persistGeneratedImage(
            ByteArray(0), "jpeg", AvatarGenerationMode.TEXT_TO_IMAGE, "m", "p", "h")
        assertFalse(empty.success)
        assertTrue(empty.errorMessage != null)
        assertTrue(repo.listVersions().isEmpty())

        val oversize = repo.persistGeneratedImage(
            ByteArray(AvatarAssetLimits.DEFAULT_MAX_IMPORT_BYTES + 1), "jpeg",
            AvatarGenerationMode.TEXT_TO_IMAGE, "m", "p", "h")
        assertFalse(oversize.success)
        assertTrue(repo.listVersions().isEmpty())
    }

    @Test
    fun `generated versions interleave newest-first with local imports`() = runTest {
        val repo = FakeAvatarAssetRepository()
        repo.importLocalImage(ByteArray(16), "photo", "image/jpeg")
        repo.persistGeneratedImage(
            ByteArray(32), "png", AvatarGenerationMode.TEXT_TO_IMAGE, "seedream-3", "prompt", "h")
        val versions = repo.listVersions()
        assertEquals(2, versions.size)
        // Newest (generated) first.
        assertTrue(versions.first().provider == "seedream")
        assertEquals(setOf("seedream", "local-import"), versions.map { it.provider }.toSet())
    }

    @Test
    fun `pure generated version record helper is deterministic`() {
        val record = AvatarAssetStorageLogic.generatedVersionRecord(
            versionId = "seedream-1",
            createdAt = "2025-03-01 00:00",
            relativeImagePath = "assets/seedream-1.png",
            mode = AvatarGenerationMode.TEXT_TO_IMAGE,
            model = "seedream-3",
            prompt = "prompt",
            profileHash = "h",
        )
        assertEquals("seedream", record.provider)
        assertEquals("seedream-1", record.versionId)
        assertEquals("seedream-3", record.model)
    }
}
